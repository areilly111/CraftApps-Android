#!/usr/bin/env bash
# Re-pin the DesignCraft upstream to a new tag and re-apply the port's changes.
# Usage: scripts/pin-upstream-designcraft.sh <tag>   (e.g. scripts/pin-upstream-designcraft.sh v0.5.1)
#
# The port keeps exactly these changes inside upstream/:
#   1. apps/designcraft-android/  — the port crate (not part of upstream; copied
#      from the old checkout into the new one by this script)
#   2. Cargo.toml                 — [workspace.dependencies] gains `caseless` and
#      `tempfile` (needed by crates/engine, which the Android port builds)
#   3. crates/engine/Cargo.toml   — `caseless` dep, `tempfile` for non-wasm32
#   4. xtask/src/layers.rs        — one line registering the crate as Exempt
#   5. Cargo.lock                 — gains the port's extra deps; regenerated by
#      cargo on the next build, not hand-edited.
#
# NOTE: designcraft-ui-egui has no eframe dependency, so there is no eframe
# accesskit gate to re-apply (the Android port crate declares its own eframe
# without accesskit; the desktop apps/designcraft crate is never built for
# Android).
#
# Everything is LOCAL. This script never pushes.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <tag>" >&2; exit 1; }
TAG="$1"
APP="designcraft"
MONOREPO="$HOME/workspace/craftapps-android"
UPSTREAM_DIR="$MONOREPO/$APP/upstream"
UPSTREAM_REPO="https://github.com/storytold/designcraft.git"
WORK="/tmp/pin-$APP-$$"

# 1. the port crate must exist in the current checkout
[ -f "$UPSTREAM_DIR/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: apps/$APP-android not found in $UPSTREAM_DIR — cannot pin" >&2
    exit 1
}

# 2. clone pristine upstream at the new tag
echo "cloning $UPSTREAM_REPO at $TAG..."
git clone --depth 1 --branch "$TAG" "$UPSTREAM_REPO" "$WORK/pristine" 2>&1 | tail -1

# 3. copy the port crate into the pristine checkout
cp -r "$UPSTREAM_DIR/apps/$APP-android" "$WORK/pristine/apps/"
[ -f "$WORK/pristine/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: port crate copy failed" >&2; rm -rf "$WORK"; exit 1
}

cd "$WORK/pristine"

# 4. re-apply the workspace dep additions
if ! grep -q '^caseless = "0.2"$' Cargo.toml; then
    python3 - <<'EOF'
p = 'Cargo.toml'
s = open(p).read()
old = 'unicode-segmentation = "1"\n'
assert old in s, "workspace deps anchor not found; patch Cargo.toml by hand"
s = s.replace(old, old + 'caseless = "0.2"\n', 1)
open(p, 'w').write(s)
print("re-applied workspace dep: caseless")
EOF
fi
if ! grep -q '^tempfile = "3"$' Cargo.toml; then
    python3 - <<'EOF'
p = 'Cargo.toml'
s = open(p).read()
old = 'regex = { version = "1", default-features = false, features = ["std", "unicode", "perf"] }\n'
assert old in s, "workspace deps regex anchor not found; patch Cargo.toml by hand"
s = s.replace(old, old + 'tempfile = "3"\n', 1)
open(p, 'w').write(s)
print("re-applied workspace dep: tempfile")
EOF
fi

# 5. re-apply the crates/engine/Cargo.toml additions
if ! grep -q 'caseless = { workspace = true }' crates/engine/Cargo.toml; then
    python3 - <<'EOF'
p = 'crates/engine/Cargo.toml'
s = open(p).read()
old = 'quick-xml = { workspace = true }\n'
assert old in s, "engine deps anchor not found; patch crates/engine/Cargo.toml by hand"
new = (old
       + 'caseless = { workspace = true }\n'
       + '\n'
       + '[target.\'cfg(not(target_arch = "wasm32"))\'.dependencies]\n'
       + 'tempfile = { workspace = true }\n')
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied crates/engine/Cargo.toml deps")
EOF
fi

# 6. re-apply the one-line layers registration
if ! grep -q '("android", Class::Exempt)' xtask/src/layers.rs; then
    python3 - <<'EOF'
p = 'xtask/src/layers.rs'
s = open(p).read()
old = '    ("web", Class::Exempt),\n'
assert old in s, "layers.rs web-exempt line not found; patch it by hand"
s = s.replace(old, old + '    ("android", Class::Exempt),\n', 1)
open(p, 'w').write(s)
print("re-applied the layers.rs registration")
EOF
fi

# 7. unified versioning: VERSION_NAME is managed at release time
# (see scripts/release.sh), NOT bumped here. The pin only updates
# upstream source; the port keeps its current unified version.
CURVN="$(grep -oP 'pub const VERSION_NAME: &str = "\K[^"]+' "apps/$APP-android/src/lib.rs")"
echo "VERSION_NAME stays at $CURVN (unified; bump via scripts/release.sh)"

# 8. swap the new upstream into place
rm -rf "$UPSTREAM_DIR"
mv "$WORK/pristine" "$UPSTREAM_DIR"
rm -rf "$WORK"
echo "pinned to $TAG. Next: scripts/build-apk.sh $APP (cargo refreshes Cargo.lock automatically)."
