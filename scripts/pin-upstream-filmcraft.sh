#!/usr/bin/env bash
# Re-pin the FilmCraft upstream to a new tag and re-apply the port's changes.
# Usage: scripts/pin-upstream-filmcraft.sh <tag>   (e.g. scripts/pin-upstream-filmcraft.sh v0.5.1)
#
# The port keeps exactly these changes inside upstream/:
#   1. apps/filmcraft-android/  — the port crate (not part of upstream; copied
#      from the old checkout into the new one by this script)
#   2. Cargo.toml               — [workspace.dependencies] gains `filmcraft-tts`
#      and `filmcraft-tts-text` (path deps the Android port's ui-egui needs)
#   3. crates/ui-egui/Cargo.toml —
#      a. gains `filmcraft-tts` and `filmcraft-export` deps (TTS voices and the
#         export pipeline the Android shell wires up)
#      b. eframe's `accesskit` feature gated off on Android (compile error with
#         eframe's android-native-activity); the single eframe line is replaced
#         by two target-specific sections
#   4. Cargo.lock               — gains the port's extra deps; regenerated by
#      cargo on the next build, not hand-edited.
#
# NOTE: filmcraft has no xtask/src/layers.rs, so there is no layers
# registration to re-apply.
#
# Everything is LOCAL. This script never pushes.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <tag>" >&2; exit 1; }
TAG="$1"
APP="filmcraft"
MONOREPO="$HOME/workspace/craftapps-android"
UPSTREAM_DIR="$MONOREPO/$APP/upstream"
UPSTREAM_REPO="https://github.com/storytold/filmcraft.git"
WORK="/tmp/pin-$APP-$$"

[ -f "$UPSTREAM_DIR/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: apps/$APP-android not found in $UPSTREAM_DIR — cannot pin" >&2
    exit 1
}

echo "cloning $UPSTREAM_REPO at $TAG..."
git clone --depth 1 --branch "$TAG" "$UPSTREAM_REPO" "$WORK/pristine" 2>&1 | tail -1

cp -r "$UPSTREAM_DIR/apps/$APP-android" "$WORK/pristine/apps/"
[ -f "$WORK/pristine/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: port crate copy failed" >&2; rm -rf "$WORK"; exit 1
}

cd "$WORK/pristine"

# re-apply the workspace dep additions
if ! grep -q '^filmcraft-tts = ' Cargo.toml; then
    python3 - <<'EOF'
p = 'Cargo.toml'
s = open(p).read()
old = 'filmcraft-speech = { path = "crates/speech" }\n'
assert old in s, "workspace deps anchor not found; patch Cargo.toml by hand"
new = (old
       + 'filmcraft-tts = { path = "crates/tts" }\n'
       + 'filmcraft-tts-text = { path = "crates/tts-text" }\n')
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied workspace deps: filmcraft-tts, filmcraft-tts-text")
EOF
fi

# re-apply the ui-egui dep additions
if ! grep -q '^filmcraft-tts = { workspace = true }$' crates/ui-egui/Cargo.toml; then
    python3 - <<'EOF'
p = 'crates/ui-egui/Cargo.toml'
s = open(p).read()
old = 'filmcraft-project = { workspace = true }\n'
assert old in s, "ui-egui deps anchor not found; patch it by hand"
s = s.replace(old, old + 'filmcraft-tts = { workspace = true }\n', 1)
open(p, 'w').write(s)
print("re-applied ui-egui dep: filmcraft-tts")
EOF
fi
if ! grep -q '^filmcraft-export = { workspace = true }$' crates/ui-egui/Cargo.toml; then
    python3 - <<'EOF'
p = 'crates/ui-egui/Cargo.toml'
s = open(p).read()
old = 'filmcraft-engine = { workspace = true }\n'
assert old in s, "ui-egui engine anchor not found; patch it by hand"
s = s.replace(old, old + 'filmcraft-export = { workspace = true }\n', 1)
open(p, 'w').write(s)
print("re-applied ui-egui dep: filmcraft-export")
EOF
fi

# re-apply the eframe accesskit gate
if ! grep -q 'cfg(target_os = "android")' crates/ui-egui/Cargo.toml; then
    python3 - <<'EOF'
p = 'crates/ui-egui/Cargo.toml'
s = open(p).read()
old = 'eframe = { workspace = true, features = ["default_fonts", "wgpu", "accesskit"] }\n'
assert old in s, "ui-egui eframe dep line not found; patch it by hand"
new = ('# eframe\'s `accesskit` (screen-reader) integration is a compile error with\n'
       '# `android-native-activity` (eframe 0.36.2), so the Android port builds eframe\n'
       '# without it. The `egui::accesskit` types used across this crate are unaffected\n'
       '# (they come from egui itself, not the eframe feature).\n'
       '[target.\'cfg(not(target_os = "android"))\'.dependencies]\n'
       'eframe = { workspace = true, features = ["default_fonts", "wgpu", "accesskit"] }\n'
       '[target.\'cfg(target_os = "android")\'.dependencies]\n'
       'eframe = { workspace = true, features = ["default_fonts", "wgpu"] }\n')
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied the ui-egui eframe accesskit gate")
EOF
fi

# unified versioning: VERSION_NAME is managed at release time
# (see scripts/release.sh), NOT bumped here. The pin only updates
# upstream source; the port keeps its current unified version.
CURVN="$(grep -oP 'pub const VERSION_NAME: &str = "\K[^"]+' "apps/$APP-android/src/lib.rs")"
echo "VERSION_NAME stays at $CURVN (unified; bump via scripts/release.sh)"
echo "VERSION_NAME: $OLDVN -> $NEWVN"

rm -rf "$UPSTREAM_DIR"
mv "$WORK/pristine" "$UPSTREAM_DIR"
rm -rf "$WORK"
echo "pinned to $TAG. Next: scripts/build-apk.sh $APP (cargo refreshes Cargo.lock automatically)."
