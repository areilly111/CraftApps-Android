#!/usr/bin/env bash
# Re-pin the EffectCraft upstream to a new tag and re-apply the port's changes.
# Usage: scripts/pin-upstream-effectcraft.sh <tag>   (e.g. scripts/pin-upstream-effectcraft.sh v0.7.1)
#
# The port keeps exactly these changes inside upstream/:
#   1. apps/effectcraft-android/  — the port crate (not part of upstream; copied
#      from the old checkout into the new one by this script)
#   2. Cargo.toml                 — default-members excludes the android crate
#      (its android-activity/JNI deps don't build for host targets)
#   3. crates/ui-egui/Cargo.toml  — eframe's `accesskit` feature gated off on
#      Android (compile error with eframe's android-native-activity); the base
#      eframe drops accesskit and a target-specific section re-adds it for
#      non-Android
#   4. Cargo.lock                 — gains the port's extra deps; regenerated by
#      cargo on the next build, not hand-edited.
#
# NOTE: effectcraft has no xtask/src/layers.rs, so there is no layers
# registration to re-apply.
#
# Everything is LOCAL. This script never pushes.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <tag>" >&2; exit 1; }
TAG="$1"
APP="effectcraft"
MONOREPO="$HOME/workspace/craftapps-android"
UPSTREAM_DIR="$MONOREPO/$APP/upstream"
UPSTREAM_REPO="https://github.com/storytold/effectcraft.git"
WORK="/tmp/pin-$APP-$$"

[ -f "$UPSTREAM_DIR/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: apps/$APP-android not found in $UPSTREAM_DIR — cannot pin" >&2
    exit 1
}

echo "cloning $UPSTREAM_REPO at $TAG..."
git clone --depth 1 --branch "$TAG" "$UPSTREAM_REPO" "$WORK/pristine" 2>&1 | tail -1

cp -r "$UPSTREAM_DIR/apps/$APP-android" "$WORK/pristine/apps/"
[ -f "$WORK/pristine/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: port crate copy failed" >&2; rm -rf "$WORK"; exit 1
}

cd "$WORK/pristine"

# re-apply the default-members exclusion
if ! grep -q 'stays out of the default set' Cargo.toml; then
    python3 - <<'EOF'
p = 'Cargo.toml'
s = open(p).read()
import re
m = re.search(r'^default-members = \[.*\]\n', s, re.M)
assert m, "default-members line not found; patch Cargo.toml by hand"
old = m.group(0)
new = ('# The Android port is built explicitly (`cargo check -p effectcraft-android\n'
       '# --target aarch64-linux-android`); its android-activity / JNI deps don\'t\n'
       '# build for host targets, so it stays out of the default set (the\n'
       '# vectorcraft-android port does the same).\n'
       'default-members = ["crates/*", "apps/effectcraft", "apps/effectcraft-cli", "apps/effectcraft-web"]\n')
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied default-members exclusion")
EOF
fi

# re-apply the eframe accesskit gate
if ! grep -q 'cfg(not(target_os = "android"))' crates/ui-egui/Cargo.toml; then
    python3 - <<'EOF'
p = 'crates/ui-egui/Cargo.toml'
s = open(p).read()
old = 'eframe = { workspace = true, features = ["default_fonts", "wgpu", "accesskit"] }\n'
assert old in s, "ui-egui eframe dep line not found; patch it by hand"
new = ('eframe = { workspace = true, features = ["default_fonts", "wgpu"] }\n')
s = s.replace(old, new, 1)
anchor = '[target.\'cfg(not(target_arch = "wasm32"))\'.dependencies]\n'
assert anchor in s, "wasm32 target section not found; patch it by hand"
addition = (anchor
            + '\n'
            + '# eframe 0.36.2 refuses `accesskit` + `android-native-activity` together\n'
            + '# (compile_error in its lib.rs), and the Android port needs the latter while\n'
            + '# nothing in this crate uses accesskit APIs; the desktop app enables the\n'
            + '# feature itself. So accesskit stays on everywhere except Android.\n'
            + '[target.\'cfg(not(target_os = "android"))\'.dependencies]\n'
            + 'eframe = { workspace = true, features = ["accesskit"] }\n')
s = s.replace(anchor, addition, 1)
open(p, 'w').write(s)
print("re-applied the ui-egui eframe accesskit gate")
EOF
fi

# unified versioning: VERSION_NAME is managed at release time
# (see scripts/release.sh), NOT bumped here. The pin only updates
# upstream source; the port keeps its current unified version.
CURVN="$(grep -oP 'pub const VERSION_NAME: &str = "\K[^"]+' "apps/$APP-android/src/lib.rs")"
echo "VERSION_NAME stays at $CURVN (unified; bump via scripts/release.sh)"
echo "VERSION_NAME: $OLDVN -> $NEWVN"

rm -rf "$UPSTREAM_DIR"
mv "$WORK/pristine" "$UPSTREAM_DIR"
rm -rf "$WORK"
echo "pinned to $TAG. Next: scripts/build-apk.sh $APP (cargo refreshes Cargo.lock automatically)."
