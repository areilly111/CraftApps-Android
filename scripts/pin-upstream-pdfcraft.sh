#!/usr/bin/env bash
# Re-pin the PdfCraft upstream to a new tag and re-apply the port's changes.
# Usage: scripts/pin-upstream-pdfcraft.sh <tag>   (e.g. scripts/pin-upstream-pdfcraft.sh v0.5.1)
#
# The port keeps exactly these changes inside upstream/:
#   1. apps/pdfcraft-android/  — the port crate (not part of upstream; copied
#      from the old checkout into the new one by this script)
#   2. crates/ui-egui/Cargo.toml —
#      a. eframe's `accesskit` feature gated off on Android (compile error with
#         eframe's android-native-activity); base eframe drops accesskit, and a
#         target-specific section re-adds it for non-Android
#      b. `rfd` and `arboard` have no Android backend: moved from unconditional
#         deps into a target section excluding wasm32 and Android
#   3. Cargo.lock              — gains the port's extra deps; regenerated by
#      cargo on the next build, not hand-edited.
#
# NOTE: pdfcraft has no xtask/src/layers.rs android registration, and its
# workspace default-members already excludes the android crate upstream.
#
# Everything is LOCAL. This script never pushes.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <tag>" >&2; exit 1; }
TAG="$1"
APP="pdfcraft"
MONOREPO="$HOME/workspace/craftapps-android"
UPSTREAM_DIR="$MONOREPO/$APP/upstream"
UPSTREAM_REPO="https://github.com/storytold/pdfcraft.git"
WORK="/tmp/pin-$APP-$$"

[ -f "$UPSTREAM_DIR/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: apps/$APP-android not found in $UPSTREAM_DIR — cannot pin" >&2
    exit 1
}

echo "cloning $UPSTREAM_REPO at $TAG..."
git clone --depth 1 --branch "$TAG" "$UPSTREAM_REPO" "$WORK/pristine" 2>&1 | tail -1

cp -r "$UPSTREAM_DIR/apps/$APP-android" "$WORK/pristine/apps/"
[ -f "$WORK/pristine/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: port crate copy failed" >&2; rm -rf "$WORK"; exit 1
}

cd "$WORK/pristine"

# re-apply the eframe accesskit gate
if ! grep -q 'cfg(not(target_os = "android"))' crates/ui-egui/Cargo.toml; then
    python3 - <<'EOF'
p = 'crates/ui-egui/Cargo.toml'
s = open(p).read()
old = 'eframe = { workspace = true, features = ["default_fonts", "wgpu", "accesskit", "persistence", "links"] }\n'
assert old in s, "ui-egui eframe dep line not found; patch it by hand"
new = 'eframe = { workspace = true, features = ["default_fonts", "wgpu", "persistence", "links"] }\n'
s = s.replace(old, new, 1)
anchor = '[target.\'cfg(not(target_arch = "wasm32"))\'.dependencies]\n'
assert anchor in s, "wasm32 target section not found; patch it by hand"
addition = ('\n'
            '# eframe\'s accesskit integration is a compile error with android-native-activity (see eframe\n'
            '# 0.36.2 src/lib.rs); `egui::accesskit` itself stays available on Android.\n'
            '[target.\'cfg(not(target_os = "android"))\'.dependencies]\n'
            'eframe = { workspace = true, features = ["accesskit"] }\n')
s = s.replace(anchor, anchor + addition, 1)
open(p, 'w').write(s)
print("re-applied the ui-egui eframe accesskit gate")
EOF
fi

# re-apply the rfd/arboard target gate
if ! grep -q 'cfg(not(any(target_arch = "wasm32", target_os = "android")))' crates/ui-egui/Cargo.toml; then
    python3 - <<'EOF'
p = 'crates/ui-egui/Cargo.toml'
s = open(p).read()
old_rfd = 'rfd = { workspace = true }\n'
assert old_rfd in s, "rfd dep line not found; patch it by hand"
s = s.replace(old_rfd, '', 1)
old_arb = '# Create \u25b8 Clipboard (images; already in the tree through egui-winit).\narboard = { version = "3.6", default-features = false, features = ["image-data"] }\n'
assert old_arb in s, "arboard dep block not found; patch it by hand"
s = s.replace(old_arb, '', 1)
anchor = '[target.\'cfg(not(target_arch = "wasm32"))\'.dependencies]\n'
assert anchor in s, "wasm32 target section not found; patch it by hand"
new_section = ('# rfd and arboard have no Android backend (neither compiles there); the Android port answers\n'
               '# file picks from its own browser (see pickers.rs) and has no system clipboard.\n'
               '[target.\'cfg(not(any(target_arch = "wasm32", target_os = "android")))\'.dependencies]\n'
               'rfd = { workspace = true }\n'
               '# Create \u25b8 Clipboard (images; already in the tree through egui-winit).\n'
               'arboard = { version = "3.6", default-features = false, features = ["image-data"] }\n'
               '\n')
s = s.replace(anchor, new_section + anchor, 1)
open(p, 'w').write(s)
print("re-applied the rfd/arboard target gate")
EOF
fi

# unified versioning: VERSION_NAME is managed at release time
# (see scripts/release.sh), NOT bumped here. The pin only updates
# upstream source; the port keeps its current unified version.
CURVN="$(grep -oP 'pub const VERSION_NAME: &str = "\K[^"]+' "apps/$APP-android/src/lib.rs")"
echo "VERSION_NAME stays at $CURVN (unified; bump via scripts/release.sh)"
echo "VERSION_NAME: $OLDVN -> $NEWVN"

rm -rf "$UPSTREAM_DIR"
mv "$WORK/pristine" "$UPSTREAM_DIR"
rm -rf "$WORK"
echo "pinned to $TAG. Next: scripts/build-apk.sh $APP (cargo refreshes Cargo.lock automatically)."
