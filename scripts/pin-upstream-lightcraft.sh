#!/usr/bin/env bash
# Re-pin the LightCraft upstream to a new tag and re-apply the port's changes.
# Usage: scripts/pin-upstream-lightcraft.sh <tag>   (e.g. scripts/pin-upstream-lightcraft.sh v0.5.1)
#
# The port keeps exactly these changes inside upstream/:
#   1. apps/lightcraft-android/  — the port crate (not part of upstream; copied
#      from the old checkout into the new one by this script)
#   2. Cargo.toml                — [workspace.dependencies] gains `rav1e` and
#      `avif-serialize` (HDR AVIF encoding; the Android port builds the avif
#      feature which needs them directly)
#   3. xtask/src/layers.rs       — one line registering the crate as Exempt
#   4. Cargo.lock                — gains the port's extra deps; regenerated by
#      cargo on the next build, not hand-edited.
#
# NOTE: the desktop apps/lightcraft crate keeps its own eframe features (it is
# never built for Android); the Android port crate declares its own eframe
# without accesskit, so there is no eframe gate to re-apply upstream.
#
# Everything is LOCAL. This script never pushes.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <tag>" >&2; exit 1; }
TAG="$1"
APP="lightcraft"
MONOREPO="$HOME/workspace/craftapps-android"
UPSTREAM_DIR="$MONOREPO/$APP/upstream"
UPSTREAM_REPO="https://github.com/storytold/lightcraft.git"
WORK="/tmp/pin-$APP-$$"

[ -f "$UPSTREAM_DIR/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: apps/$APP-android not found in $UPSTREAM_DIR — cannot pin" >&2
    exit 1
}

echo "cloning $UPSTREAM_REPO at $TAG..."
git clone --depth 1 --branch "$TAG" "$UPSTREAM_REPO" "$WORK/pristine" 2>&1 | tail -1

cp -r "$UPSTREAM_DIR/apps/$APP-android" "$WORK/pristine/apps/"
[ -f "$WORK/pristine/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: port crate copy failed" >&2; rm -rf "$WORK"; exit 1
}

cd "$WORK/pristine"

# re-apply the workspace dep additions
if ! grep -q '^rav1e = ' Cargo.toml; then
    python3 - <<'EOF'
p = 'Cargo.toml'
s = open(p).read()
old = 'ravif = { version = "0.13", default-features = false, features = ["threading"] } # no "asm": it needs nasm (non-Rust)\n'
assert old in s, "workspace ravif anchor not found; patch Cargo.toml by hand"
new = (old
       + '# HDR AVIF (PQ): ravif fixes the sRGB transfer curve, so HDR files drive its rav1e + avif-serialize directly\n'
       + 'rav1e = { version = "0.8.1", default-features = false, features = ["threading"] }\n'
       + 'avif-serialize = "0.8.6"\n')
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied workspace deps: rav1e, avif-serialize")
EOF
fi

# re-apply the one-line layers registration
if ! grep -q '("android", Class::Exempt)' xtask/src/layers.rs; then
    python3 - <<'EOF'
p = 'xtask/src/layers.rs'
s = open(p).read()
old = '    ("web", Class::Exempt),\n'
assert old in s, "layers.rs web-exempt line not found; patch it by hand"
s = s.replace(old, old + '    ("android", Class::Exempt),\n', 1)
open(p, 'w').write(s)
print("re-applied the layers.rs registration")
EOF
fi

# unified versioning: VERSION_NAME is managed at release time
# (see scripts/release.sh), NOT bumped here. The pin only updates
# upstream source; the port keeps its current unified version.
CURVN="$(grep -oP 'pub const VERSION_NAME: &str = "\K[^"]+' "apps/$APP-android/src/lib.rs")"
echo "VERSION_NAME stays at $CURVN (unified; bump via scripts/release.sh)"
echo "VERSION_NAME: $OLDVN -> $NEWVN"

rm -rf "$UPSTREAM_DIR"
mv "$WORK/pristine" "$UPSTREAM_DIR"
rm -rf "$WORK"
echo "pinned to $TAG. Next: scripts/build-apk.sh $APP (cargo refreshes Cargo.lock automatically)."
