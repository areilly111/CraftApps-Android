#!/usr/bin/env bash
# Re-pin the VectorCraft upstream to a new tag and re-apply the port's changes.
# Usage: scripts/pin-upstream-vectorcraft.sh <tag>   (e.g. scripts/pin-upstream-vectorcraft.sh v0.8.1)
#
# The port keeps exactly these changes inside upstream/:
#   1. apps/vectorcraft-android/  — the port crate (not part of upstream; copied
#      from the old checkout into the new one by this script)
#   2. Cargo.toml                 — [workspace.dependencies] gains
#      `vectorcraft-three-d` (the 3D crate the Android port builds), and
#      `vello_cpu` gains the `f32_pipeline` feature (the Android renderer
#      needs it; the default integer pipeline mis-renders on GLES)
#   3. xtask/src/layers.rs        — register `three-d` as Layer(2) with its
#      dependency edges, plus the `android` Exempt line for the port crate
#   4. Cargo.lock                 — gains the port's extra deps; regenerated by
#      cargo on the next build, not hand-edited.
#
# NOTE: the desktop apps/vectorcraft crate keeps its own eframe features (it is
# never built for Android); the Android port crate declares its own eframe
# without accesskit, so there is no eframe gate to re-apply upstream.
#
# Everything is LOCAL. This script never pushes.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <tag>" >&2; exit 1; }
TAG="$1"
APP="vectorcraft"
MONOREPO="$HOME/workspace/craftapps-android"
UPSTREAM_DIR="$MONOREPO/$APP/upstream"
UPSTREAM_REPO="https://github.com/storytold/vectorcraft.git"
WORK="/tmp/pin-$APP-$$"

[ -f "$UPSTREAM_DIR/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: apps/$APP-android not found in $UPSTREAM_DIR — cannot pin" >&2
    exit 1
}

echo "cloning $UPSTREAM_REPO at $TAG..."
git clone --depth 1 --branch "$TAG" "$UPSTREAM_REPO" "$WORK/pristine" 2>&1 | tail -1

cp -r "$UPSTREAM_DIR/apps/$APP-android" "$WORK/pristine/apps/"
[ -f "$WORK/pristine/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: port crate copy failed" >&2; rm -rf "$WORK"; exit 1
}

cd "$WORK/pristine"

# re-apply the three-d workspace dep
if ! grep -q '^vectorcraft-three-d = ' Cargo.toml; then
    python3 - <<'EOF'
p = 'Cargo.toml'
s = open(p).read()
old = 'vectorcraft-effects = { path = "crates/effects" }\n'
assert old in s, "workspace deps anchor not found; patch Cargo.toml by hand"
s = s.replace(old, old + 'vectorcraft-three-d = { path = "crates/three-d" }\n', 1)
open(p, 'w').write(s)
print("re-applied workspace dep: vectorcraft-three-d")
EOF
fi

# re-apply the vello_cpu f32_pipeline feature
if ! grep -q 'vello_cpu = { version = "0.2", features = \["f32_pipeline"\] }' Cargo.toml; then
    python3 - <<'EOF'
p = 'Cargo.toml'
s = open(p).read()
old = 'vello_cpu = "0.2"\n'
assert old in s, "vello_cpu dep line not found; patch Cargo.toml by hand"
new = 'vello_cpu = { version = "0.2", features = ["f32_pipeline"] }\n'
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied vello_cpu f32_pipeline feature")
EOF
fi

# re-apply the three-d layers registration
if ! grep -q '("three-d", Class::Layer(2))' xtask/src/layers.rs; then
    python3 - <<'EOF'
p = 'xtask/src/layers.rs'
s = open(p).read()
old = '    ("effects", Class::Layer(2)),\n'
assert old in s, "layers.rs effects line not found; patch it by hand"
s = s.replace(old, old + '    ("three-d", Class::Layer(2)),\n', 1)
open(p, 'w').write(s)
print("re-applied layers.rs: three-d registration")
EOF
fi

# re-apply the three-d dependency edges
if ! grep -q '&\["three-d", "effects"\]' xtask/src/layers.rs; then
    python3 - <<'EOF'
p = 'xtask/src/layers.rs'
s = open(p).read()
old = '    &["plugins", "effects"],\n'
assert old in s, "layers.rs plugins edge not found; patch it by hand"
if '&["pdf", "eps"],' not in s:
    new = (old
           + '    // Non-native art in Illustrator editing data is a PDF, drawn by the PDF importer.\n'
           + '    &["pdf", "eps"],\n'
           + '    &["three-d", "effects"],\n')
else:
    new = old + '    &["three-d", "effects"],\n'
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied layers.rs: three-d dependency edges")
EOF
fi

# re-apply the android exempt registration
if ! grep -q '("android", Class::Exempt)' xtask/src/layers.rs; then
    python3 - <<'EOF'
p = 'xtask/src/layers.rs'
s = open(p).read()
old = '    ("web", Class::Exempt),\n'
assert old in s, "layers.rs web-exempt line not found; patch it by hand"
s = s.replace(old, old + '    // The Android port shell (NativeActivity + JNI): host-only, exempt like the other apps.\n'
              + '    ("android", Class::Exempt),\n', 1)
open(p, 'w').write(s)
print("re-applied layers.rs: android exempt registration")
EOF
fi

# unified versioning: VERSION_NAME is managed at release time
# (see scripts/release.sh), NOT bumped here. The pin only updates
# upstream source; the port keeps its current unified version.
CURVN="$(grep -oP 'pub const VERSION_NAME: &str = "\K[^"]+' "apps/$APP-android/src/lib.rs")"
echo "VERSION_NAME stays at $CURVN (unified; bump via scripts/release.sh)"
echo "VERSION_NAME: $OLDVN -> $NEWVN"

rm -rf "$UPSTREAM_DIR"
mv "$WORK/pristine" "$UPSTREAM_DIR"
rm -rf "$WORK"
echo "pinned to $TAG. Next: scripts/build-apk.sh $APP (cargo refreshes Cargo.lock automatically)."
