#!/usr/bin/env bash
# Re-pin the upstream checkout to a new tag and re-apply the port's changes.
# Usage: scripts/pin-upstream.sh <tag>   (e.g. scripts/pin-upstream.sh v0.7.0)
#
# The port keeps exactly three changes inside upstream/:
#   1. apps/photocraft-android/  — the port crate (untracked by upstream git;
#      `git checkout` never touches it, but this script verifies it's intact)
#   2. xtask/src/layers.rs      — one line registering the crate as Exempt
#   3. crates/ui-egui/Cargo.toml — eframe's `accesskit` feature gated off on
#      Android (compile error with eframe's android-native-activity)
#   4. Cargo.lock               — gains the port's extra deps (android_logger
#      etc.); regenerated by cargo on the next build, not hand-edited.
#
# Everything is LOCAL. This script never pushes.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <tag>" >&2; exit 1; }
TAG="$1"
UPSTREAM="$HOME/workspace/photocraft-android/upstream"

cd "$UPSTREAM"
git fetch --tags origin
git checkout "$TAG"

# 1. the port crate must have survived the checkout (it's untracked upstream)
[ -f apps/photocraft-android/src/lib.rs ] || {
    echo "FATAL: apps/photocraft-android vanished on checkout — restore it before building" >&2
    exit 1
}

# 2. re-apply the one-line layers registration if the checkout dropped it
if ! grep -q '("android", Class::Exempt)' xtask/src/layers.rs; then
    python3 - <<'EOF'
p = 'xtask/src/layers.rs'
s = open(p).read()
old = '    ("web", Class::Exempt),\n'
assert old in s, "layers.rs L7 block not found; patch it by hand"
s = s.replace(old, old + '    ("android", Class::Exempt),\n', 1)
open(p, 'w').write(s)
print("re-applied the layers.rs registration")
EOF
fi

# 3. re-apply the Android eframe feature gate if the checkout dropped it
if ! grep -q 'cfg(not(target_os = "android"))' crates/ui-egui/Cargo.toml; then
    python3 - <<'EOF'
p = 'crates/ui-egui/Cargo.toml'
s = open(p).read()
old = 'eframe = { workspace = true, features = ["default_fonts", "wgpu", "accesskit"] }\n'
assert old in s, "ui-egui eframe dep line not found; patch it by hand"
new = ('# eframe\'s `accesskit` (screen-reader) integration is a compile error with\n'
       '# `android-native-activity` (eframe 0.36.2), so the Android port builds eframe\n'
       '# without it. The `egui::accesskit` types used across this crate are unaffected\n'
       '# (they come from egui itself, not the eframe feature).\n'
       '[target.\'cfg(not(target_os = "android"))\'.dependencies]\n'
       'eframe = { workspace = true, features = ["default_fonts", "wgpu", "accesskit"] }\n'
       '[target.\'cfg(target_os = "android")\'.dependencies]\n'
       'eframe = { workspace = true, features = ["default_fonts", "wgpu"] }\n')
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied the ui-egui Android eframe gate")
EOF
fi

# 3. bump the port version: VERSION_NAME in the Rust crate, e.g. 0.6.0-port1 -> 0.7.0-port1
UPVER="${TAG#v}"
RSLIB="apps/photocraft-android/src/lib.rs"
OLDVN="$(grep -oP 'pub const VERSION_NAME: &str = "\K[^"]+' "$RSLIB")"
NEWVN="$UPVER-port1"
sed -i "s/pub const VERSION_NAME: &str = \"$OLDVN\"/pub const VERSION_NAME: &str = \"$NEWVN\"/" "$RSLIB"
echo "VERSION_NAME: $OLDVN -> $NEWVN"

echo "pinned to $TAG. Next: scripts/build-apk.sh (cargo refreshes Cargo.lock automatically)."
